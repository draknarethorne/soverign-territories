def publish(catalog, out, *, library_root, reports_prefix="../", section_links=None):
    target = pathlib.Path(out) / PAGE
    if target.is_symlink():
        raise ValueError(f"linked fictional relationship report refused: {target}")
    content = render_html(catalog, library_root=library_root, reports_prefix=reports_prefix,
                          section_links=section_links).encode("utf-8")
    target.write_bytes(content)
    return {PAGE: content}


def reports_current(out):
    out = pathlib.Path(out)
    target = out / PAGE
    try:
        receipt = json.loads((out / "people-gallery-manifest.json").read_text(encoding="utf-8"))
        return (not target.is_symlink() and target.is_file()
                and hashlib.sha256(target.read_bytes()).hexdigest() == receipt.get("files", {}).get(PAGE))
    except (OSError, ValueError, TypeError, AttributeError):
        return False

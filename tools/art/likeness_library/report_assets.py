"""Record only exact regenerated People report bytes for lean snapshot ownership."""
import hashlib
import json
import os
import pathlib
import shutil
import tempfile
import time

MANIFEST = "people-gallery-manifest.json"
RECIPE = "people-gallery-v1"


PUBLISH_RETRY_DELAYS = (0.05, 0.1, 0.2, 0.4, 1, 2, 4, 8, 15)


def _retry_locked(action, target, operation, *args):
    for attempt, delay in enumerate((*PUBLISH_RETRY_DELAYS, None)):
        try:
            operation(*args)
            return
        except PermissionError:
            if delay is None:
                raise
            if attempt == 0 or delay >= 1:
                print(f"DIAGNOSTIC: temporary file lock {action} {target}; retrying in {delay}s", flush=True)
            time.sleep(delay)


def _publish(operation, stage, target):
    _retry_locked("publishing", target, operation, stage, target)


def replace_file(stage, target):
    _publish(os.replace, stage, target)


def rename_directory(stage, target):
    """Keep new-directory rename semantics while retrying temporary scanner locks."""
    _publish(os.rename, stage, target)


def remove_tree(path):
    """Delete scratch output whose freshly written files a scanner may still hold open."""
    _retry_locked("removing", path, lambda: shutil.rmtree(path) if os.path.lexists(path) else None)


def record(out, payloads):
    out = pathlib.Path(out)
    manifest = out / MANIFEST
    previous = json.loads(manifest.read_text(encoding="utf-8")) if manifest.is_file() else {}
    files = {}
    if previous.get("recipe") == RECIPE and previous.get("formatVersion") == 1:
        for name, expected in previous.get("files", {}).items():
            relative = pathlib.PurePosixPath(name)
            if relative.is_absolute() or ".." in relative.parts or "\\" in name:
                raise ValueError(f"unsafe generated report record: {name}")
            target = out / relative
            if target.is_file() and not target.is_symlink() and hashlib.sha256(target.read_bytes()).hexdigest() == expected:
                files[name] = expected
    for name, payload in payloads.items():
        relative = pathlib.PurePosixPath(name)
        if relative.is_absolute() or ".." in relative.parts or "\\" in name:
            raise ValueError(f"unsafe generated report path: {name}")
        target = out / relative
        expected = hashlib.sha256(payload).hexdigest()
        if target.is_file() and not target.is_symlink() and target.read_bytes() == payload:
            files[name] = expected
        else:
            files.pop(name, None)
            print(f"DIAGNOSTIC: report asset differs from regenerated bytes; retained in backups: {target}")
    value = (json.dumps({"formatVersion": 1, "recipe": RECIPE, "files": files},
                        sort_keys=True, indent=2) + "\n").encode()
    if not manifest.is_file() or manifest.read_bytes() != value:
        stage = None
        try:
            with tempfile.NamedTemporaryFile(dir=out, prefix=".people-assets-", suffix=".tmp", delete=False) as output:
                stage = pathlib.Path(output.name)
                output.write(value)
            replace_file(stage, manifest)
        finally:
            if stage is not None and stage.exists():
                stage.unlink()
    thumbnail_files = [out / name for name in files if name.endswith(".jpg")]
    print(f"Managed People thumbnails: {len(thumbnail_files)} / "
          f"{sum(path.stat().st_size for path in thumbnail_files)} bytes; shared by overview/Review")

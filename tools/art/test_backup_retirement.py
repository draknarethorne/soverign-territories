"""Fail-closed unit tests plus opt-in actual Windows Recycle Bin proof.

python tools\\art\\test_backup_retirement.py
python tools\\art\\test_backup_retirement.py --physical

The physical test invokes bin\\backup-retire.cmd, preserves its synthetic source,
baseline, independent bundles, proof trees, receipts and sealed results under
ignored tmp\\retire-proof. It never opens a production backup or writes on B:.
The legacy fixture retains the production manifest field shape (exclude_backup)
using only freshly generated bytes. It is not evidence to retire old production
backlog: that backlog remains held.
"""
